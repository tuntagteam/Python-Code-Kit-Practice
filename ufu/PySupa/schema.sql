-- =========================================================
-- EXAMPLE SQL QUERIES
-- =========================================================

-- 1. Show all menu items
SELECT
    m.menu_item_id,
    c.category_name,
    m.item_name,
    m.price,
    m.is_available
FROM menu_items m
JOIN categories c
    ON c.category_id = m.category_id
ORDER BY c.category_name, m.item_name;

-- 2. Show complete order details
SELECT
    o.order_id,
    o.order_date,
    cu.full_name AS customer_name,
    o.order_type,
    o.order_status,
    m.item_name,
    oi.quantity,
    oi.unit_price,
    oi.line_total
FROM orders o
LEFT JOIN customers cu
    ON cu.customer_id = o.customer_id
JOIN order_items oi
    ON oi.order_id = o.order_id
JOIN menu_items m
    ON m.menu_item_id = oi.menu_item_id
ORDER BY o.order_id, oi.order_item_id;

-- 3. Calculate sales per order from order_items
SELECT
    o.order_id,
    SUM(oi.line_total) AS calculated_subtotal,
    o.discount_amount,
    o.delivery_fee,
    SUM(oi.line_total) - o.discount_amount + o.delivery_fee AS calculated_total
FROM orders o
JOIN order_items oi
    ON oi.order_id = o.order_id
GROUP BY
    o.order_id,
    o.discount_amount,
    o.delivery_fee
ORDER BY o.order_id;

-- 4. Top-selling menu items
SELECT
    m.item_name,
    SUM(oi.quantity) AS total_quantity_sold,
    SUM(oi.line_total) AS total_sales
FROM order_items oi
JOIN orders o
    ON o.order_id = oi.order_id
JOIN menu_items m
    ON m.menu_item_id = oi.menu_item_id
WHERE o.order_status = 'COMPLETED'
GROUP BY m.menu_item_id, m.item_name
ORDER BY total_quantity_sold DESC, total_sales DESC;

-- 5. Daily revenue
SELECT
    DATE(order_date AT TIME ZONE 'Asia/Bangkok') AS sales_date,
    COUNT(*) AS total_orders,
    SUM(total_amount) AS revenue
FROM orders
WHERE order_status = 'COMPLETED'
GROUP BY DATE(order_date AT TIME ZONE 'Asia/Bangkok')
ORDER BY sales_date;

-- 6. Revenue by payment method
SELECT
    payment_method,
    COUNT(*) AS payment_count,
    SUM(amount) AS total_amount
FROM payments
WHERE payment_status = 'PAID'
GROUP BY payment_method
ORDER BY total_amount DESC;

-- 7. Find orders from a specific customer
SELECT
    o.order_id,
    o.order_date,
    o.order_type,
    o.order_status,
    o.total_amount
FROM orders o
JOIN customers c
    ON c.customer_id = o.customer_id
WHERE c.full_name = 'Narin Chaiyaporn'
ORDER BY o.order_date DESC;

-- 8. Show available food under 70 THB
SELECT
    item_name,
    price
FROM menu_items
WHERE is_available = TRUE
  AND price < 70
ORDER BY price ASC;

